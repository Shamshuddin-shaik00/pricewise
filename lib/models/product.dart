class Product {
  final String id;
  final String name;
  final String category;
  final String unit;
  final double lowestPrice;
  final int shopCount;
  final String emoji;

  Product({
    required this.id,
    required this.name,
    required this.category,
    required this.unit,
    required this.lowestPrice,
    required this.shopCount,
    required this.emoji,
  });
}